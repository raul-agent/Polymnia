#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Multimodal dataset creation pipeline:

- Downloads clips and processes them with TalkNet‑ASD.
- Filters to a single speaker and runs Argos (OpenPose + dfMaker).
- Generates parquet, acoustic analysis (ecos / apate) and DuckDB.
- Supports resuming (--resume) and starting directly at Argos (--start_at_argos).

Author: DaedalusLAB
"""

import argparse
import os
import concurrent.futures
import sys
import re 

# Path to this script itself
script_dir = os.path.dirname(os.path.abspath(__file__))
os.environ["PYTHON_SCRIPT_DIR"] = script_dir  # for the R scripts

# Adjust this path to your TalkNet‑ASD installation
ASD_PATH = "/home/user/TalkNet-ASD"

# ---------- common utilities --------------------------------------------------

def run_command(command: str) -> int:
    """Runs a shell command and returns its exit code."""
    print(f"Running: {command}")
    return os.system(command)

def check_json_generated(output_folder: str) -> bool:
    """Returns True if JSON_FILES folders generated by OpenPose already exist."""
    openpose_dir = os.path.join(output_folder, "dataset", "OpenPose")
    if not os.path.exists(openpose_dir):
        return False
    return any(
        os.path.isdir(os.path.join(openpose_dir, vid, "JSON_FILES"))
        for vid in os.listdir(openpose_dir)
    )

def check_parquet_generated(output_folder: str) -> bool:
    """Returns True if .parquet files have already been generated."""
    parquet_dir = os.path.join(output_folder, "dataset", "1_persons", "parquet_files")
    return os.path.exists(parquet_dir) and any(
        f.endswith(".parquet") for f in os.listdir(parquet_dir)
    )

def mark_apate_ecos_done(output_folder: str) -> None:
    """Creates flag files indicating that ecos.py and apate.py finished successfully."""
    for flag in ("apate_done.txt", "ecos_done.txt"):
        with open(os.path.join(output_folder, flag), "w") as f:
            f.write("done")

def sanitize_filename(name: str) -> str:
    """Replaces problematic characters for file names."""
    return re.sub(r"[^\w\-]", "_", name)

# ---------- conditional steps -------------------------------------------------

def run_argos_if_needed(output_folder: str) -> None:
    """
    Runs argos.py (OpenPose + dfMaker) if JSON_FILES do not exist.
    Idempotent: if JSON already exist, the step is skipped.
    """
    if check_json_generated(output_folder):
        print("JSON_FILES folders already exist. Argos is not needed.")
        return

    print("No JSON_FILES found. Launching argos.py…")
    run_command(
        "python3 argos.py "
        f'--videos_folder "{os.path.join(output_folder, "videos", "1_person")}" '
        f'--output_folder "{output_folder}" '
        "--openpose_path /opt/openpose "
        "--face_hands True "
        "--skeletons True"
    )

def generate_parquet_if_needed(output_folder: str) -> None:
    """
    Generates .parquet files using max_people_classification.R
    if JSON exist but parquet still do not.
    """
    if not check_json_generated(output_folder):
        print("No JSON yet; parquet cannot be generated.")
        return
    if check_parquet_generated(output_folder):
        print("Parquet already generated. Skipping Rscript.")
        return

    print("Generating parquet files with max_people_classification.R…")
    dataset_dir = os.path.join(output_folder, "dataset")
    openpose_dir = os.path.join(dataset_dir, "OpenPose")
    for video_name in os.listdir(openpose_dir):
        json_folder = os.path.join(openpose_dir, video_name, "JSON_FILES")
        if os.path.exists(json_folder):
            print(f"→ Rscript in {json_folder}")
            run_command(
                f'Rscript max_people_classification.R "{json_folder}" "{dataset_dir}"'
            )

def run_missing_voice_scripts(output_folder: str) -> None:
    """
    Runs ecos.py and/or apate.py if their 'done' flags are still missing.
    """
    tasks = []
    for name in ("apate", "ecos"):
        flag = os.path.join(output_folder, f"{name}_done.txt")
        if not os.path.exists(flag):
            cmd = f'python3 {name}.py --input_folder {output_folder} --n_persons 1'
            tasks.append((name, cmd, flag))

    if not tasks:
        print("ecos.py and apate.py are already marked as completed.")
        return

    print("Running missing voice analyses…")
    with concurrent.futures.ThreadPoolExecutor() as ex:
        futures = {ex.submit(run_command, cmd): (name, flag) for name, cmd, flag in tasks}
        for fut in concurrent.futures.as_completed(futures):
            name, flag = futures[fut]
            if fut.result() == 0:
                print(f"{name}.py finished successfully.")
                with open(flag, "w") as f:
                    f.write("done")
            else:
                print(f"⚠️  {name}.py failed (flag not created).")

def build_duckdb_if_needed(output_folder: str) -> None:
    """
    Generates dataset.duckdb if it does not exist yet, after interactive confirmation.
    """
    db_path = os.path.join(output_folder, "dataset.duckdb")
    if os.path.exists(db_path):
        print("dataset.duckdb already exists.")
        return
    ans = input("Do you want to generate dataset.duckdb now? (y/n): ").strip().lower()
    if ans == "y":
        run_command(
            f'python3 hefesto.py --input_folder "{output_folder}" --n_persons 1 '
            f'--db_name "{db_path}"'
        )

# ---------- recovery routines -------------------------------------------------

def run_recovery(output_folder: str) -> None:
    """Recovery path (`--resume`)."""
    run_argos_if_needed(output_folder)
    generate_parquet_if_needed(output_folder)
    if check_parquet_generated(output_folder):
        run_missing_voice_scripts(output_folder)
    else:
        print("Without parquet: ecos/apate cannot be executed yet.")
    build_duckdb_if_needed(output_folder)

# ---------- main workflow -----------------------------------------------------

def main() -> None:
    p = argparse.ArgumentParser(
        description="Multimodal dataset creation pipeline."
    )
    p.add_argument("--input", required=True, help="txt generated by tabulate")
    p.add_argument("--output_folder", required=True, help="Output folder")
    p.add_argument("--searchterm", required=True, help="Search term")
    p.add_argument("--offset", type=int, default=2, help="Offset in seconds")
    p.add_argument("--check_hands", action="store_true", help="Check hands")
    p.add_argument("--resume", action="store_true", help="Resume process")
    p.add_argument(
        "--start_at_argos",
        action="store_true",
        help="Start directly at the Argos/OpenPose step",
    )
    p.add_argument(
        "--skip_download",
        action="store_true",
        help="Assume the videos are already in videos/raw",
    )
    args = p.parse_args()

    out_dir = args.output_folder
    os.makedirs(out_dir, exist_ok=True)

    # ---------- recovery mode -------------------------------------------------
    if args.resume:
        print("==> Recovery mode (--resume)")
        run_recovery(out_dir)
        return

    # ---------- start at Argos mode ------------------------------------------
    if args.start_at_argos:
        print("==> Direct start at Argos (--start_at_argos)")
        run_argos_if_needed(out_dir)
        generate_parquet_if_needed(out_dir)
        run_missing_voice_scripts(out_dir)

        # DuckDB construction with name based on searchterm
        db_filename = f"{sanitize_filename(args.searchterm)}.duckdb"
        duckdb_path = os.path.join(out_dir, db_filename)
        if not os.path.exists(duckdb_path):
            print(f"Generating {db_filename} directly (mode --start_at_argos)…")
            run_command(
                f'python3 hefesto.py --input_folder "{out_dir}" '
                f'--n_persons 1 --db_name "{duckdb_path}"'
            )
        else:
            print(f"{db_filename} already exists.")

        return

    # ---------- full workflow from scratch -----------------------------------
    if not args.skip_download:
        print("Downloading clips...")
        run_command(
            f'python3 download_clips.py --txt_file "{args.input}" '
            f'--searchterm "{args.searchterm}" '
            f'--output_dir "{out_dir}/videos/raw" --offset {args.offset}'
        )
    else:
        print("🔹 Skip download: assuming videos/raw ready.")

    # ASD processing
    in_raw = os.path.abspath(f"{out_dir}/videos/raw")
    out_masked = os.path.abspath(f"{out_dir}/videos/masked")
    print("Processing with TalkNet‑ASD…")
    run_command(
        f'cd "{ASD_PATH}" && ./process_video.py '
        f'--input_dir "{in_raw}" --output_dir "{out_masked}" '
        f'--second {args.offset}'
    )

    # Filter to one speaker
    run_command(
        "python3 is_there_a_person_in_the_video.py "
        f'--videos_folder "{out_masked}" '
        f'--discarded_videos "{out_dir}/videos/discarded" '
        f'--matched_videos "{out_dir}/videos/1_person" '
        f'--check_hands {args.check_hands}'
    )

    # Argos and subsequent steps
    run_argos_if_needed(out_dir)
    generate_parquet_if_needed(out_dir)

    # Voice analysis in parallel
    print("Running voice analysis (ecos/apate)…")
    with concurrent.futures.ThreadPoolExecutor() as ex:
        fut_ecos = ex.submit(
            run_command, f'python3 ecos.py --input_folder "{out_dir}" --n_persons 1'
        )
        fut_apate = ex.submit(
            run_command, f'python3 apate.py --input_folder "{out_dir}" --n_persons 1'
        )
        concurrent.futures.wait([fut_ecos, fut_apate])

    if fut_ecos.result() == 0 and fut_apate.result() == 0:
        mark_apate_ecos_done(out_dir)
        print("ecos.py and apate.py completed successfully.")
    else:
        print("⚠️  ecos/apate failed. Retry with --resume.")

    # DuckDB construction
    run_command(
        f'python3 hefesto.py --input_folder "{out_dir}" '
        f'--n_persons 1 --db_name "{out_dir}/dataset.duckdb"'
    )

    # Copy “good” videos
    good_dir = os.path.join(out_dir, "videos", "good")
    os.makedirs(good_dir, exist_ok=True)
    parquet_dir = os.path.join(out_dir, "dataset", "1_persons", "parquet_files")
    if os.path.exists(parquet_dir):
        for pq in os.listdir(parquet_dir):
            if pq.endswith(".parquet"):
                mp4 = pq.replace(".parquet", ".mp4")
                src = os.path.join(out_dir, "videos", "raw", mp4)
                if os.path.exists(src):
                    run_command(f'cp "{src}" "{good_dir}/{mp4}"')

if __name__ == "__main__":
    main()
